"""Regenerate the data-driven pgfplots figures from the recorded results.

  fig2-encoder-ablation.tex   per-seed macro-F1 and AUROC of the four payload encoders
                              (reproducibility/kaggle_gpu_v2/runs, graph read-out, seeds 0-1)
  fig4-shift-dumbbell.tex     in-distribution vs held-out AUROC of six detectors on five benchmarks
                              (reproducibility/kaggle_gpu_v4 and reproducibility/detectors_v4)

    python sp2027/figures/make_data_figures.py
"""
from __future__ import annotations

import glob
import json
import re
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from summarise_detectors import cell, collect, unpack  # noqa: E402

ENC = [("minilm", "one vector per message", "cE1"), ("chunk", "chunks: mean + max", "cE2"),
       ("chunk_lex", "+ per-chunk word vector", "cE3"), ("chunk_mil", "+ learned chunk scoring", "cE4")]
EBENCH = [("mcptox", "MCPTox"), ("mcp_safetybench", "MCP-SafetyBench"), ("agentdojo", "AgentDojo")]


def encoder_runs() -> dict:
    out: dict = {}
    for f in glob.glob(str(ROOT / "reproducibility/kaggle_gpu_v2/runs/*.json")):
        m = re.search(r"(enc|main)__(\w+?)__full__(\w+?)__all__seed(\d)", Path(f).name)
        if not m or (m.group(1) == "main" and int(m.group(4)) > 1):
            continue
        t = json.load(open(f))["test_at_val_threshold"]
        out.setdefault((m.group(2), m.group(3)), []).append((t["macro_f1"], t["auroc"]))
    return out


def fig2() -> str:
    runs = encoder_runs()
    w, off = 0.17, [-0.27, -0.09, 0.09, 0.27]
    panels = []
    for k, (metric, ylab, ymin) in enumerate([(0, "test macro-F1", 0.4), (1, "test AUROC", 0.4)]):
        body = []
        for j, (enc, _, col) in enumerate(ENC):
            bars = " ".join(f"({i + 1 + off[j]:.2f},{np.mean([r[metric] for r in runs[(b, enc)]]):.4f})"
                            for i, (b, _) in enumerate(EBENCH))
            dots = " ".join(f"({i + 1 + off[j]:.2f},{r[metric]:.4f})" for i, (b, _) in enumerate(EBENCH)
                            for r in runs[(b, enc)])
            body.append(f"\\addplot[ybar, bar width={w}, bar shift=0pt, fill={col}, draw=figInk!60, line width=0.3pt]"
                        f" coordinates {{{bars}}};")
            body.append(f"\\addplot[only marks, mark=*, mark size=0.9pt, figInk, forget plot] coordinates {{{dots}}};")
        xt = "xticklabels={MCPTox,MCP-SafetyBench,AgentDojo}," if k == 1 else "xticklabels={},"
        legend = ("legend style={at={(0.5,1.04)}, anchor=south, legend columns=2, "
                  "/tikz/every even column/.append style={column sep=6pt}}, area legend," if k == 0 else "")
        name = "name=fa," if k == 0 else "at={(fa.south)}, anchor=north, yshift=-0.25cm,"
        panels.append(
            f"\\begin{{axis}}[sci, {name} width=\\columnwidth, height=3.55cm, ymin={ymin}, ymax=1.03, "
            f"xmin=0.5, xmax=3.5, xtick={{1,2,3}}, {xt} ytick={{0.4,0.6,0.8,1.0}}, ylabel={{{ylab}}}, "
            f"extra y ticks={{0.5}}, extra y tick labels={{}}, extra y tick style={{grid=major, major grid style="
            f"{{densely dashed, figInk!55, line width=0.5pt}}}}, {legend}]\n" + "\n".join(body) +
            ("\n\\legend{" + ", ".join(e[1] for e in ENC) + "}" if k == 0 else "") + "\n\\end{axis}")
    return ("% fig2-encoder-ablation (generated by make_data_figures.py): bars = mean of seeds 0-1, dots = seeds\n"
            "\\begin{tikzpicture}\n" + "\n".join(panels) + "\n\\end{tikzpicture}\n")


DET = [("neural", "MambaGuard", "cDet", "*"), ("lexical", "Lexical", "cLex", "square*"),
       ("deberta_ft", "DeBERTa-v3 ft.", "cDeb", "diamond*"), ("llmjudge", "LLM judge", "cJud", "triangle*"),
       ("protectai", "ProtectAI", "cPro", "pentagon*"), ("piguard", "PIGuard", "cPig", "otimes*")]
DBENCH = [("a2a_sandbox", "A2A sandbox"), ("mcptox", "MCPTox"), ("mcp_safetybench", "MCP-SafetyBench"),
          ("agentdojo", "AgentDojo"), ("injecagent", "InjecAgent")]


def fig4() -> str:
    res = collect(unpack([ROOT / "reproducibility/kaggle_gpu_v4", ROOT / "reproducibility/detectors_v4"]))
    n = len(DET)
    out = ["% fig4-shift-dumbbell (generated by make_data_figures.py)",
           "\\resizebox{\\textwidth}{!}{%", "\\begin{tikzpicture}",
           "\\begin{groupplot}[group style={group size=5 by 1, horizontal sep=0.25cm, y descriptions at=edge left},",
           f"  sci, width=4.15cm, height=4.6cm, xmin=0.1, xmax=1.04, ymin=0.4, ymax={n + 0.6},",
           "  xtick={0.25,0.5,0.75,1.0}, xticklabels={.25,.5,.75,1}, xmajorgrids, ymajorgrids=false,",
           f"  ytick={{{','.join(str(n - i) for i in range(n))}}}, yticklabels={{{','.join(d[1] for d in DET)}}},",
           "  xlabel={test AUROC}, y tick label style={font=\\scriptsize}, axis lines*=left]"]
    for b, title in DBENCH:
        out.append(f"\\nextgroupplot[title={{{title}}}]")
        out.append(f"\\draw[densely dashed, figInk!50, line width=0.5pt] (axis cs:0.5,0.4) -- (axis cs:0.5,{n + 0.6});")
        for i, (d, _, col, mark) in enumerate(DET):
            y = n - i
            a, h = cell(res, "main", d, b), cell(res, "heldout", d, b)
            out.append(f"\\draw[{col}, line width=1.1pt] (axis cs:{a:.3f},{y}) -- (axis cs:{h:.3f},{y});")
            out.append(f"\\addplot[only marks, mark={mark}, mark size=2.1pt, {col}, mark options={{draw=white, line width=0.3pt}}]"
                       f" coordinates {{({a:.3f},{y})}};")
            out.append(f"\\addplot[only marks, mark={mark.rstrip('*')}, mark size=2.1pt, {col}, mark options={{fill=white, line width=0.8pt}}]"
                       f" coordinates {{({h:.3f},{y})}};")
    out += ["\\end{groupplot}",
            "\\node[anchor=north, font=\\scriptsize, text=figInk] at ($(group c3r1.south)+(0,-0.75)$) {%",
            "  \\tikz\\draw[figInk, fill=figInk] (0,0) circle (2pt); in distribution \\quad",
            "  \\tikz\\draw[figInk, fill=white, line width=0.8pt] (0,0) circle (2pt); held-out templates \\quad",
            "  \\tikz\\draw[densely dashed, figInk!50, line width=0.5pt] (0,0) -- (0.5,0); chance};",
            "\\end{tikzpicture}}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    (HERE / "fig2-encoder-ablation.tex").write_text(fig2())
    (HERE / "fig4-shift-dumbbell.tex").write_text(fig4())
    print("wrote fig2-encoder-ablation.tex and fig4-shift-dumbbell.tex")
