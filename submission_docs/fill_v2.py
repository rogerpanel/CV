"""Robust template filler operating directly on word/document.xml.

Strategy: extract the docx zip, edit document.xml as raw text with
ordered string replacements, repack. This avoids python-docx's
run-splitting issues and catches placeholders that span runs.
"""
import zipfile, shutil, os, re, io

SRC = '/home/user/CV/submission_docs/source'
DST = '/home/user/CV/submission_docs/filled'

os.makedirs(DST, exist_ok=True)


def docx_replace(src_path, dst_path, ordered_replacements):
    """Repack src docx into dst docx, doing string substitutions on
    word/document.xml. ordered_replacements is a list of (old, new)
    tuples applied in order (so longer/more specific keys come first).
    """
    shutil.copy(src_path, dst_path)
    with zipfile.ZipFile(src_path, 'r') as zin:
        data = {n: zin.read(n) for n in zin.namelist()}
    xml = data['word/document.xml'].decode('utf-8')
    # XML escape for the values (but keep our content)
    for old, new in ordered_replacements:
        # Escape ampersands and angle brackets in new value
        new_esc = (new.replace('&', '&amp;')
                      .replace('<', '&lt;')
                      .replace('>', '&gt;'))
        # Soft text replacement: directly on XML (text nodes contain
        # the placeholder strings literally without entity escaping
        # unless they were typed with brackets etc.)
        if old in xml:
            xml = xml.replace(old, new_esc)
    # Also collapse cross-run placeholders: strip the XML tags
    # between adjacent text nodes to get a flat text view, then
    # search again.  We rebuild the XML by removing intervening
    # </w:t>...<w:t> sequences within a single <w:r> chain — only
    # safe within identical run properties, which we approximate by
    # joining adjacent <w:r>...</w:r> runs that have no rPr
    # difference.  Simpler approach: handle each placeholder by
    # searching for "<w:t...>...placeholder-prefix" patterns.
    # We perform a second pass that strips inter-run tags between
    # <w:t> tags for the duration of each placeholder if it spans.
    def split_run_replace(xml_text, old, new):
        # Build a regex that allows arbitrary XML between each character of `old`
        # (only for placeholders short enough to be safe)
        if len(old) > 200 or old in xml_text:
            return xml_text
        # Allow runs to be split: <something/> between chars
        pat_chars = []
        for ch in old:
            esc = re.escape(ch)
            pat_chars.append(esc)
        # Between characters allow </w:t>...</w:r><w:r>...<w:t>
        sep = r'(?:</w:t>(?:(?!</w:p>).)*?<w:t[^>]*>)?'
        pattern = sep.join(pat_chars)
        new_esc = (new.replace('&', '&amp;')
                      .replace('<', '&lt;')
                      .replace('>', '&gt;'))
        try:
            return re.sub(pattern, new_esc, xml_text, count=0)
        except re.error:
            return xml_text

    for old, new in ordered_replacements:
        xml = split_run_replace(xml, old, new)

    data['word/document.xml'] = xml.encode('utf-8')
    with zipfile.ZipFile(dst_path, 'w', zipfile.ZIP_DEFLATED) as zout:
        for n, b in data.items():
            zout.writestr(n, b)


