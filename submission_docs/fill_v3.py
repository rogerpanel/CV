def build_doc3():
    src = os.path.join(SRC, 'e5433faa-kaf_22_2.3.1.docx')
    dst = os.path.join(DST, '03_Protokol_zasedaniya_kafedry_22.docx')

    # Doc 3 fills only candidate's section. We perform paragraph-level
    # substitutions but FIRST narrow xml to candidate's block.
    with zipfile.ZipFile(src, 'r') as zin:
        data = {n: zin.read(n) for n in zin.namelist()}
    xml = data['word/document.xml'].decode('utf-8')

    # Header replacement on whole doc
    xml = xml.replace(
        'ПРОТОКОЛ № _______ от «____» _______________ 2026 г.',
        'ПРОТОКОЛ № ___ от «04» июня 2026 г.')

    # Find candidate's block (between markers)
    # We use paragraph-level walk and only modify paragraphs whose
    # candidate-name marker has been seen and the next-candidate
    # marker hasn't been seen yet.
    out = []
    last = 0
    in_block = False
    for m in P_OPEN.finditer(xml):
        end = xml.find('</w:p>', m.end())
        if end == -1:
            continue
        end_full = end + len('</w:p>')
        p_xml = xml[m.start():end_full]
        out.append(xml[last:m.start()])

        ptext = paragraph_text(p_xml)
        if 'Анаедевху Роджер-Ника' in ptext and ('Аспиранта' in ptext or 'СЛУШАЛИ' in ptext):
            in_block = True
        elif 'Аспиранта' in ptext and 'Анаедевху' not in ptext:
            in_block = False

        if in_block:
            new = ptext
            # Targeted replacements
            new = new.replace('рукопись диссертации в объеме ___ страниц',
                              'рукопись диссертации в объёме 301 страницу')
            new = new.replace('положительный / отрицательный отзыв руководителя.',
                              'положительный отзыв руководителя.')
            new = re.sub(r'(приравненных к журналам из Перечня ВАК\):\s*)_+',
                         r'\g<1>5', new)
            new = re.sub(r'(в иных научных журналах[^.]*в пункте выше:\s*)_+',
                         r'\g<1>0', new, flags=re.DOTALL)
            new = re.sub(r'(в пункте выше:\s*)_+', r'\g<1>0', new)
            new = re.sub(r'представлены на\s*_+\s*конференциях, из них на\s*_+\s*конференциях за последние два года',
                         'представлены на 8 конференциях, из них на 8 конференциях за последние два года', new)
            new = re.sub(r'На защиту выносится\s*_+\s*научных положений, основное содержание\s*_+\s*из них',
                         'На защиту выносится 6 научных положений, основное содержание 4 из них', new)
            new = new.replace(
                '«Системный анализ, управление и обработка информации, статистика»: ____________________________.',
                '«Системный анализ, управление и обработка информации, статистика»: п. 4 и п. 5.')
            new = new.replace(
                'выполнена на высоким / среднем / низком уровне, работа в целом соответствует / не соответствует',
                'выполнена на высоком уровне, работа в целом соответствует')
            new = new.replace('в достаточном / недостаточном количестве',
                              'в достаточном количестве')
            new = re.sub(
                r'Аттестовать / не аттестовать аспиранта Анаедевху Роджер-Ника по «Научно-исследовательской деятельности аспиранта и подготовке к защите диссертации на соискание ученой степени кандидата наук» с оценкой\s*_+',
                'Аттестовать аспиранта Анаедевху Роджер-Ника по «Научно-исследовательской деятельности аспиранта и подготовке к защите диссертации на соискание ученой степени кандидата наук» с оценкой «отлично»', new)
            new = new.replace(
                'Аттестовать / не аттестовать аспиранта Анаедевху Роджер-Ника по «Апробации результатов научной деятельности».',
                'Аттестовать аспиранта Анаедевху Роджер-Ника по «Апробации результатов научной деятельности».')
            new = re.sub(
                r'Рекомендовать допустить\s*/\s*не допускать к итоговой аттестации аспиранта Анаедевху Роджер-Ника\.',
                'Рекомендовать допустить к итоговой аттестации аспиранта Анаедевху Роджер-Ника.', new)
            if new != ptext:
                out.append(rewrite_paragraph(p_xml, new))
            else:
                out.append(p_xml)
        else:
            out.append(p_xml)
        last = end_full
    out.append(xml[last:])
    xml = ''.join(out)

    data['word/document.xml'] = xml.encode('utf-8')
    with zipfile.ZipFile(dst, 'w', zipfile.ZIP_DEFLATED) as zout:
        for n, b in data.items():
            zout.writestr(n, b)
    print('OK doc3:', dst)


