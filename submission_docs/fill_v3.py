# Regex shortcuts
P_OPEN  = re.compile(r'<w:p\b[^>]*>', re.DOTALL)
P_CLOSE = re.compile(r'</w:p>')
T_NODE  = re.compile(r'<w:t(?:\s[^>]*)?>(.*?)</w:t>', re.DOTALL)
R_NODE  = re.compile(r'<w:r\b[^>]*>(?:(?!</w:r>).)*</w:r>', re.DOTALL)
RPR     = re.compile(r'(<w:rPr>.*?</w:rPr>)', re.DOTALL)
PPR     = re.compile(r'(<w:pPr>.*?</w:pPr>)', re.DOTALL)


def paragraph_text(p_xml):
    """Get the concatenated visible text of all <w:t> nodes, with
    non-breaking spaces normalized to regular spaces for matching."""
    return ''.join(T_NODE.findall(p_xml)).replace('\xa0', ' ')


def rewrite_paragraph(p_xml, new_text):
    """Return new <w:p>...</w:p> with single <w:r><w:t>new_text</w:t></w:r>."""
    # Preserve <w:pPr> block if any
    ppr_match = PPR.search(p_xml)
    ppr = ppr_match.group(1) if ppr_match else ''

    # Preserve <w:rPr> of first <w:r> if any (for font/size inheritance)
    first_r = R_NODE.search(p_xml)
    rpr = ''
    if first_r:
        m = RPR.search(first_r.group(0))
        if m:
            rpr = m.group(1)

    # Extract paragraph opening tag attrs
    p_open_m = P_OPEN.search(p_xml)
    p_open = p_open_m.group(0)

    # Build new paragraph
    text_xml = (new_text.replace('&', '&amp;')
                        .replace('<', '&lt;').replace('>', '&gt;'))
    # support embedded newlines via <w:br/>
    if '\n' in new_text:
        # Split lines, intersperse with <w:br/>
        lines = text_xml.split('\n')
        run_inner = (f'<w:t xml:space="preserve">{lines[0]}</w:t>'
                     + ''.join(f'<w:br/><w:t xml:space="preserve">{ln}</w:t>'
                               for ln in lines[1:]))
    else:
        run_inner = f'<w:t xml:space="preserve">{text_xml}</w:t>'
    new_run = f'<w:r>{rpr}{run_inner}</w:r>'
    return f'{p_open}{ppr}{new_run}</w:p>'


def apply_replacements_xml(xml, ordered_replacements):
    """For every paragraph in xml, try all replacements; if any matches the
    visible text, rebuild the paragraph with the new text."""
    out = []
    last = 0
    for m in P_OPEN.finditer(xml):
        # find matching </w:p>
        end = xml.find('</w:p>', m.end())
        if end == -1:
            continue
        end_full = end + len('</w:p>')
        p_xml = xml[m.start():end_full]
        out.append(xml[last:m.start()])

        ptext = paragraph_text(p_xml)
        new_text = ptext
        for old, new in ordered_replacements:
            if old in new_text:
                new_text = new_text.replace(old, new)

        if new_text != ptext:
            out.append(rewrite_paragraph(p_xml, new_text))
        else:
            out.append(p_xml)
        last = end_full
    out.append(xml[last:])
    return ''.join(out)


def docx_replace(src_path, dst_path, ordered_replacements):
    with zipfile.ZipFile(src_path, 'r') as zin:
        data = {n: zin.read(n) for n in zin.namelist()}
    xml = data['word/document.xml'].decode('utf-8')
    xml = apply_replacements_xml(xml, ordered_replacements)
    data['word/document.xml'] = xml.encode('utf-8')
    with zipfile.ZipFile(dst_path, 'w', zipfile.ZIP_DEFLATED) as zout:
        for n, b in data.items():
            zout.writestr(n, b)


