"""Robust template filler v3: works at paragraph level.

For every <w:p>...</w:p> paragraph in document.xml we:
  1. Extract concatenated visible text (all <w:t>...</w:t> nodes)
  2. Apply ordered replacements
  3. If any replacement matched, rebuild the paragraph with a SINGLE
     <w:r><w:rPr>...</w:rPr><w:t>NEW TEXT</w:t></w:r> while preserving
     paragraph-level properties (<w:pPr>) and run-level properties of
     the FIRST original run.

This sacrifices in-paragraph formatting (e.g. coloured placeholders)
but reliably catches placeholders that span runs, which is the whole
point of filling these templates.
"""
