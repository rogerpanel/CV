def apply(file_path, rename_map, inserts):
    with open(file_path, 'r', encoding='utf-8') as f:
        s = f.read()
    n_renames = 0
    for old, new in rename_map.items():
        if old in s:
            s = s.replace(old, new)
            n_renames += 1
    n_inserts = 0
    for anchor, insert_block in inserts:
        if anchor in s and insert_block.strip() not in s:
            s = s.replace(anchor, insert_block + '\n' + anchor, 1)
            n_inserts += 1
    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(s)
    return n_renames, n_inserts


